const fs=require('fs');
const assert=require('node:assert/strict');
const {chromium}=require('C:/Users/alexi/AppData/Local/ms-playwright-go/1.57.0/package');
const base=process.env.CER_QA_BASE_URL || 'http://127.0.0.1:3000';
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:1000}});
 const errors=[];const resourceErrors=[];const layouts=[];
 page.on('pageerror',e=>errors.push(e.message));
 page.on('response',r=>{if(r.status()>=400)resourceErrors.push({status:r.status(),url:r.url()});});
 const pages=[['/',1],['/ahorros',3],['/cuarteles',2],['/simulador',1]];
 for(const width of [320,390,768,1440]){
  await page.setViewportSize({width,height:1000});
  for(const [route,count] of pages){
   const response=await page.goto(base+route,{waitUntil:'networkidle'});
   assert.equal(response.status(),200,route);
   await page.waitForTimeout(100);
   const charts=page.locator('main svg[role="img"]');
   assert.equal(await charts.count(),count,route+' chart count');
   const layout=await page.evaluate(()=>({viewport:innerWidth,document:document.documentElement.scrollWidth}));
   assert.ok(layout.document<=width+1,route+' overflow at '+width);
   const labels=await charts.locator('text').evaluateAll(items=>items.map(item=>parseFloat(getComputedStyle(item).fontSize)));
   assert.ok(labels.every(size=>size>=12),route+' font size');
   layouts.push({width,route,charts:count,...layout,minimumLabelPx:Math.min(...labels)});
  }
 }
 await page.goto(base+'/ahorros',{waitUntil:'networkidle'});
 const cumulative=await page.locator('[data-chart="savings-cumulative"] circle[data-value]').evaluateAll(items=>items.map(item=>Number(item.dataset.value)));
 assert.deepEqual(cumulative,[18,45,80,121,169,214]);
 const contributions=await page.locator('[data-chart="savings-contribution"] rect[data-value]').evaluateAll(items=>items.map(item=>Number(item.dataset.value)));
 assert.deepEqual(contributions,[96,71,47]);
 assert.equal(contributions.reduce((a,b)=>a+b,0),214);
 await page.getByRole('button',{name:'Febrero',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Febrero',exact:true}).getAttribute('aria-pressed'),'true');
 for(const summary of await page.locator('main summary').all())await summary.click();
 assert.equal(await page.locator('main table:visible').count(),3);
 await page.goto(base+'/cuarteles',{waitUntil:'networkidle'});
 assert.match(await page.locator('[data-chart="parcel-moisture"] desc').textContent(),/Cuartel 2: 19/);
 assert.match(await page.locator('[data-chart="parcel-savings"] desc').textContent(),/^Cuartel 4:.*236/);
 await page.locator('main summary').first().click();
 await page.getByRole('link',{name:'Cuartel 2 - Santina Sur',exact:true}).click();
 await page.waitForURL('**/cuarteles?cuartel=2');
 assert.match(await page.locator('#cuarteles').innerText(),/Cuartel 2 - Santina Sur/);
 await page.goto(base+'/simulador',{waitUntil:'networkidle'});
 const water=page.locator('[data-chart="simulator-costs"] rect[data-cost="Agua y riego"][data-scenario="CER"]');
 assert.equal(Number(await water.getAttribute('data-value')),281200);
 const slider=page.getByRole('slider',{name:'Porcentaje de ahorro en agua',exact:true});
 await slider.focus();await slider.press('End');
 await page.waitForTimeout(100);
 assert.equal(await slider.inputValue(),'40');
 assert.equal(Number(await water.getAttribute('data-value')),228000);
 const scenario=await page.locator('[data-chart="simulator-costs"] rect[data-scenario="CER"]').evaluateAll(items=>items.reduce((sum,item)=>sum+Number(item.dataset.value),0));
 assert.equal(scenario,717700);
 await page.getByText('Ver datos de costos del escenario',{exact:true}).click();
 assert.match(await page.locator('tfoot').innerText(),/272\.300/);
 await page.setViewportSize({width:390,height:1000});
 await page.addStyleTag({content:'header { position:static !important; }'});
 await page.locator('[data-chart="simulator-costs"]').locator('..').screenshot({path:'agentes/diseno/simulador-costos-390.png'});
 const cdp=await page.context().newCDPSession(page);
 await cdp.send('Emulation.setEmulatedVisionDeficiency',{type:'deuteranopia'});
 await page.goto(base+'/ahorros',{waitUntil:'networkidle'});
 await page.screenshot({path:'agentes/diseno/ahorros-deuteranopia-390.png',fullPage:true});
 await cdp.send('Emulation.setEmulatedVisionDeficiency',{type:'none'});
 assert.equal(errors.length,0,errors.join('\n'));
 const report={layouts,cumulative,contributions,simulator:{waterScenarioBefore:281200,waterScenarioAfter:228000,totalScenarioAfter:scenario,savingAfter:272300},errors,resourceErrors,accessibility:'SVG con titulo y descripcion; fuente>=12px; tablas y enlaces comprobados; seleccion de mes y slider con teclado; captura deuteranopia'};
 fs.writeFileSync('agentes/funcionamiento/VERIFICACION_GRAFICOS.json',JSON.stringify(report,null,2));
 console.log(JSON.stringify({checks:layouts.length,cumulative,contributions,simulator:report.simulator,errors,resourceErrors},null,2));
 await browser.close();
})().catch(error=>{console.error(error);process.exitCode=1;});
